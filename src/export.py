"""Run the whole pipeline and write the outputs.

    python -m src.export            # writes into data/

data/processed/  every table as CSV with a "# SYNTHETIC DATA" header comment (for humans)
data/supabase/   the same tables without the comment line, because Postgres COPY and the
                 Supabase importer would read it as a data row; SYNTHETIC_DATA.md sits next to them
data/contracts/  three sample contract PDFs
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from src.config import ROOT, load_config
from src.contracts_pdf import build_contract_pdfs
from src.forecast import forecast, fy_landing, landing_by_category
from src.generate import generate
from src.recommend import recommend
from src.variance import variance, waterfall

# Tables loaded into Supabase, in dependency order (matches sql/schema.sql).
SUPABASE_TABLES = ["scenario", "vendors", "contracts", "monthly_spend", "budget", "headcount",
                   "benchmarks", "savings", "forecast_monthly", "variance", "recommendations"]
# Extra, human-readable outputs (the views compute the same figures inside the database).
REPORT_TABLES = ["fy_landing", "fy_landing_by_category", "variance_waterfall"]


def build_tables(cfg: dict) -> dict[str, pd.DataFrame]:
    data = generate(cfg)
    fc = forecast(data, cfg)
    landing = fy_landing(data, fc, cfg)
    var = variance(data, fc, cfg)
    sc, th = cfg["scenario"], cfg["thresholds"]
    scenario = pd.DataFrame([dict(
        scenario_id=1, anchor_date=sc["anchor_date"], fiscal_year=sc["fiscal_year"], currency=sc.get("currency", "BRL"),
        ipca_annual_pct=cfg["economics"]["ipca_annual_pct"], renewal_window_days=th["renewal_window_days"],
        near_term_renewal_days=th["near_term_renewal_days"], urgent_deadline_days=th["urgent_deadline_days"],
        seed=cfg["seed"])])
    wf = pd.concat([waterfall(var, "ytd").assign(scope="ytd"), waterfall(var, "fy_landing").assign(scope="fy_landing")])
    return dict(
        scenario=scenario, vendors=data["vendors"], contracts=data["contracts"],
        monthly_spend=data["monthly_spend"], budget=data["budget"], headcount=data["headcount"],
        benchmarks=data["benchmarks"], savings=data["savings"], forecast_monthly=fc, variance=var,
        recommendations=recommend(data, cfg), fy_landing=landing,
        fy_landing_by_category=landing_by_category(landing), variance_waterfall=wf[["scope", "step", "amount"]],
        _data=data,
    )


def _to_csv_text(df: pd.DataFrame) -> str:
    out = df.copy()
    for col in out.columns:
        if pd.api.types.is_datetime64_any_dtype(out[col]):
            out[col] = out[col].dt.strftime("%Y-%m-%d")
        elif pd.api.types.is_bool_dtype(out[col]):
            out[col] = out[col].map({True: "true", False: "false"})
        elif out[col].dtype == object and out[col].map(lambda x: isinstance(x, bool)).any():
            out[col] = out[col].map(lambda x: {True: "true", False: "false"}.get(x, x))
    return out.to_csv(index=False, lineterminator="\n")


def _header(name: str, cfg: dict) -> str:
    base = (f"# SYNTHETIC DATA - fictional fintech and fictional vendors, generated by src/generate.py "
            f"(seed {cfg['seed']}, anchor date {cfg['scenario']['anchor_date']}). Not real spend.\n")
    if name == "benchmarks":
        base += ("# Exception: reference_product, list_price, list_currency, billing_basis, source_url and as_of are "
                 "real public list prices checked on the as_of date; the vendor mapping is fictional.\n")
    return base


def run(cfg: dict, out_root: str | Path = ROOT / "data") -> dict[str, pd.DataFrame]:
    out_root = Path(out_root)
    processed, supabase = out_root / "processed", out_root / "supabase"
    processed.mkdir(parents=True, exist_ok=True)
    supabase.mkdir(parents=True, exist_ok=True)
    tables = build_tables(cfg)
    for name in SUPABASE_TABLES + REPORT_TABLES:
        text = _to_csv_text(tables[name])
        (processed / f"{name}.csv").write_text(_header(name, cfg) + text, encoding="utf-8", newline="\n")
        if name in SUPABASE_TABLES:
            (supabase / f"{name}.csv").write_text(text, encoding="utf-8", newline="\n")
    (supabase / "SYNTHETIC_DATA.md").write_text(
        "# Synthetic data\n\nEvery CSV in this folder is synthetic: a fictional fintech and fictional vendors, "
        f"generated by `src/generate.py` with seed {cfg['seed']}. The files have no comment line so that "
        "Postgres `COPY` and the Supabase importer can load them. The commented originals are in `data/processed/`.\n\n"
        "The only real-world values are the public list prices in `benchmarks.csv` (with source URL and as-of date).\n",
        encoding="utf-8", newline="\n")
    build_contract_pdfs(tables["_data"], out_root / "contracts")
    return tables


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default=str(ROOT / "config.yaml"))
    parser.add_argument("--out", default=str(ROOT / "data"))
    args = parser.parse_args()
    tables = run(load_config(args.config), args.out)
    rec = tables["recommendations"]
    print(f"Wrote {len(SUPABASE_TABLES) + len(REPORT_TABLES)} tables to {args.out}")
    print(f"Renewals in window: {len(rec)}, estimated annual impact BRL {rec['estimated_annual_impact'].sum():,.2f}")


if __name__ == "__main__":
    main()
